}

public class ItemNameTable : Dictionary<Items, string>
{
    // names are read from BinaryData\ITEMDESC.EDT at startup (LoadItemInfo, not ported yet);
    // until then every lookup yields an empty string instead of throwing.
    public new string this[Items item]
    {
        get => this.TryGetValue(item, out var s) ? s : "";
        set => base[item] = value;
    }
}

